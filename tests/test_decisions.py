class Integrity(Base):
    def setUp(self):
        super().setUp()
        self.start()
        self.add("Database engine", question=Q)
        self.add("Framework API")
        self.ok("set", "1.1.1", "doing", "--why", "started")
        self.snap = self.d / "snap"
        shutil.copytree(self.d / ".decisions", self.snap)

    def restore(self):
        shutil.rmtree(self.d / ".decisions")
        shutil.copytree(self.snap, self.d / ".decisions")

    def tamper(self, fn):
        p = self.d / ".decisions" / "log.jsonl"
        lines = p.read_text().splitlines()
        fn(lines)
        p.write_text("\n".join(lines) + "\n")

    def test_detects_each_kind_of_tampering(self):
        cases = {
            "edit": (lambda L: L.__setitem__(4, L[4].replace("scoping", "other"))),
            "delete": (lambda L: L.pop(3)),
            "truncate": (lambda L: L.pop()),
            "reorder": (lambda L: L.__setitem__(slice(3, 5), [L[4], L[3]])),
            "forge": (lambda L: L.append('{"t":"2026-01-01T00:00:00","type":"state","id":"C1","why":"forged"}')),
        }
        for name, fn in cases.items():
            with self.subTest(name):
                self.restore()
                self.tamper(fn)
                rc, out, _ = self.dec("verify")
                self.assertEqual(rc, 2, out)
                self.assertTrue("ALTERED" in out, out)
                self.assertIn("blocked", self.fail("set", "1.1.1", "done", "--chosen", "PostgreSQL 16", "--reason", "good reasons here", "--why", "x"))

    def test_index_falsification_and_rebase(self):
        self.restore()
        p = self.d / ".decisions" / "index.json"
        p.write_text(p.read_text().replace('"state": 1', '"state": 3', 1))
        rc, out, _ = self.dec("verify")
        self.assertEqual(rc, 2)
        self.assertIn("C1.state", out)
        self.restore()
        self.tamper(lambda L: L.__setitem__(4, L[4].replace("scoping", "other")))
        self.assertIn("--rebase", self.fail("seal", "--why", "x"))
        self.ok("seal", "--rebase", "--why", "known edit")
        self.assertIn("OK", self.ok("verify"))
        self.assertTrue(any(f.name.startswith("log.jsonl.before-seal") for f in (self.d / ".decisions").iterdir()))

    def test_legacy_unsealed_journal_migration(self):
        self.restore()
        p = self.d / ".decisions" / "log.jsonl"
        legacy = [json.dumps({k: v for k, v in json.loads(l).items() if k not in ("h", "prev", "rec")}) for l in p.read_text().splitlines()]
        p.write_text("\n".join(legacy) + "\n")
        rc, out, _ = self.dec("verify")
        self.assertEqual(rc, 2)
        self.assertIn("UNSEALED", out)
        self.assertIn("seal", self.fail("set", "1.1.1", "done", "--chosen", "PostgreSQL 16", "--reason", "good reasons here", "--why", "x"))
        self.ok("seal", "--why", "migration")
        self.assertIn("OK", self.ok("verify"))

    def test_document_modified_after_validation_warns(self):
        self.restore()
        self.ok("set", "1.1.1", "validated", "--chosen", "PostgreSQL 16 on RDS", "--reason", "ACID and native JSON", "--alternatives", "none", "--why", "ok")
        self.assertNotIn("⚠", self.ok("verify"))
        with open(self.d / "docs" / "decisions" / "database-engine.md", "a") as f:
            f.write("\nsneaky edit\n")
        self.assertIn("modified since its validation", self.ok("verify"))


