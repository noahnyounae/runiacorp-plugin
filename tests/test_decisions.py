"""Test suite for the decisions skill. Run: python3 -m unittest discover -s tests -v"""
import json, os, re, shutil, subprocess, sys, tempfile, unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKILL = REPO / "skills" / "decisions"
DEC = SKILL / "scripts" / "dec.py"
Q = "Which relational database stores the business data?"


def run(args, cwd, env=None, home=None):
    e = {**os.environ, "HOME": str(home or cwd), "PYTHONDONTWRITEBYTECODE": "1"}
    e.pop("DECISIONS_LANG", None)
    e.update(env or {})
    p = subprocess.run([sys.executable, str(DEC), *args], cwd=cwd, env=e, capture_output=True, text=True)
    return p.returncode, p.stdout, p.stderr


class Base(unittest.TestCase):
    def setUp(self):
        self.d = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.d, True)

    def dec(self, *a, **kw):
        return run(list(a), self.d, **kw)

    def ok(self, *a, **kw):
        rc, out, err = self.dec(*a, **kw)
        self.assertEqual(rc, 0, f"{a}: {out}{err}")
        return out

    def fail(self, *a, **kw):
        rc, out, err = self.dec(*a, **kw)
        self.assertNotEqual(rc, 0, f"{a} should fail: {out}")
        return out + err

    def start(self, lang="en", packs=1):
        self.ok("init", "--lang", lang)
        self.ok("iter-new", "MVP")
        for i in range(packs):
            self.ok("pack-new", f"Stack{'' if not i else i}")

    def add(self, title, pack="1.1", **kw):
        args = ["add", title, "--pack", pack, "--question", kw.pop("question", f"What exactly does {title} settle for us?"), "--why", "scoping"]
        for k, v in kw.items():
            args += [f"--{k}", v]
        return self.ok(*args)

    def log_lines(self):
        return (self.d / ".decisions" / "log.jsonl").read_text().splitlines()


